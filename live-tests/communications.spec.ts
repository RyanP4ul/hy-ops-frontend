import { expect, test } from "@playwright/test";
import { browserLogin } from "./helpers";

test.setTimeout(120000);
test("Communications separates SMS templates and email with previews, failure recovery and single submissions", async ({ page }) => {
  page.setDefaultTimeout(15000);
  await browserLogin(page, "staff@example.test");
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const stats = { success: true, overall: { total: 3, pending: 0, processing: 0, sent: 3, delivered: 0, failed: 0, cancelled: 0 }, today: { total: 0, sent: 0, failed: 0 }, weekly_trend: [{ date: "2026-10-30", total: 3, sent: 3, failed: 0 }], per_device: [{ device_id: "fixture-active", device_name: "Gateway phone", is_active: true, last_seen: "2026-10-30T22:56:40.425Z", total_sms: 3, sent: 3, failed: 0 }, { device_id: "inactive", device_name: "Archived phone", is_active: false, last_seen: null, total_sms: 0, sent: 0, failed: 0 }], active_devices: 1 };
  const templates = { success: true, templates: [{ id: 1, name: "Delivery notice", content: "Hi {{name}}, order {{order}} is ready.", variables: ["name", "order"], is_active: true, usage_count: 0, created_at: "2026-11-02T01:45:40.092Z" }, { id: 2, name: "Old template", content: "Inactive", variables: [], is_active: false, usage_count: 0, created_at: "2026-11-02T01:45:40.092Z" }] };
  let offline = true, smsCalls = 0, emailCalls = 0;
  let releaseSms!: () => void;
  const smsGate = new Promise<void>(resolve => { releaseSms = resolve; });
  await page.route("**/api/sms/stats", route => route.fulfill(offline ? { status: 503, json: { success: false, message: "Gateway offline" } } : { json: stats }));
  await page.route("**/api/sms/templates", route => route.fulfill({ json: templates }));
  await page.route("**/api/sms/send-sms", async route => {
    smsCalls++;
    expect(route.request().postDataJSON()).toEqual({ device_id: "fixture-active", phone_number: "09123456789", template_id: 1, variables: { name: "Pat", order: "ORDER-1" } });
    if (smsCalls === 1) return route.fulfill({ status: 502, json: { success: false, message: "SMS submission not confirmed. Check gateway." } });
    await smsGate;
    return route.fulfill({ json: { success: true, id: "sms-fixture" } });
  });
  await page.route("**/api/email/send", route => {
    emailCalls++;
    expect(route.request().postDataJSON()).toEqual({ to: "customer@example.test", subject: "Order ready", message: "Hello <script>plain text</script>" });
    return route.fulfill(emailCalls === 1 ? { status: 503, contentType: "text/plain", body: "Unavailable" } : { json: { success: true, messageId: "mail-fixture" } });
  });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/panel/communications");
  await expect(page.getByRole("heading", { name: "Communications", exact: true })).toBeVisible();
  await expect(page.getByRole("alert").filter({ hasText: "Gateway offline" })).toBeVisible();
  await expect(page.getByRole("button", { name: "Review SMS", exact: true })).toBeDisabled();
  offline = false; await page.getByRole("button", { name: "Retry SMS stats", exact: true }).click();
  const overview = page.getByRole("region", { name: "SMS gateway overview", exact: true });
  await expect(overview.getByText("Delivered", { exact: true }).locator("..").locator("dd")).toHaveText("0");
  await expect(overview.getByText("Sent", { exact: true }).locator("..").locator("dd")).toHaveText("3");
  await page.getByLabel("SMS device", { exact: true }).selectOption("fixture-active");
  await page.getByLabel("SMS template", { exact: true }).selectOption("1");
  await expect(page.getByLabel("SMS template", { exact: true }).locator("option[value='2']")).toHaveCount(0);
  await expect(page.getByLabel("SMS device", { exact: true }).locator("option[value='inactive']")).toHaveCount(0);
  const phoneInput = page.getByRole("combobox", { name: "Phone number", exact: true });
  await phoneInput.fill("(0912) 345-6789");
  await page.getByRole("option", { name: "Use custom: 09123456789", exact: true }).click();
  await page.getByLabel("name", { exact: true }).fill("  Pat  ");
  await page.getByLabel("order", { exact: true }).fill("ORDER-1");
  await expect(page.getByRole("region", { name: "SMS message preview", exact: true })).toContainText("Hi Pat, order ORDER-1 is ready.");
  await page.screenshot({ path: "D:/Project/workspace/.tmp/communications-sms-desktop.png", fullPage: true });

  await page.getByRole("tab", { name: "Email", exact: true }).click();
  await expect(page.getByLabel("Recipient email", { exact: true })).toHaveValue("");
  await page.getByRole("combobox", { name: "Recipient email", exact: true }).fill("customer@example.test");
  await page.getByRole("option", { name: "Use custom: customer@example.test", exact: true }).click();
  await page.getByLabel("Subject", { exact: true }).fill("Order ready");
  await page.getByLabel("Email message", { exact: true }).fill("Hello <script>plain text</script>");
  await page.getByRole("tab", { name: "SMS", exact: true }).click();
  await expect(page.getByLabel("Phone number", { exact: true })).toHaveValue("09123456789");
  await page.getByRole("button", { name: "Review SMS", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog).toContainText("09123456789");
  await dialog.getByRole("button", { name: "Send SMS", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("not confirmed");
  expect(smsCalls).toBe(1);
  await dialog.getByRole("button", { name: "Back to message", exact: true }).click();
  await expect(page.getByLabel("name", { exact: true })).toHaveValue("  Pat  ");
  await page.getByRole("button", { name: "Review SMS", exact: true }).click();
  await dialog.getByRole("button", { name: "Send SMS", exact: true }).click();
  await expect(dialog.getByRole("button", { name: "Sending...", exact: true })).toBeDisabled();
  expect(smsCalls).toBe(2);
  releaseSms();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("status").filter({ hasText: "SMS request accepted" })).toBeVisible();
  await expect(page.getByLabel("Phone number", { exact: true })).toHaveValue("");
  await expect(overview.getByText("Delivered", { exact: true }).locator("..").locator("dd")).toHaveText("0");

  await page.getByRole("tab", { name: "Email", exact: true }).click();
  await expect(page.getByLabel("Subject", { exact: true })).toHaveValue("Order ready");
  await page.screenshot({ path: "D:/Project/workspace/.tmp/communications-email-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Review email", exact: true }).click();
  await expect(dialog).toContainText("Hello <script>plain text</script>");
  await expect(dialog.locator("script")).toHaveCount(0);
  await dialog.getByRole("button", { name: "Send email", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("not confirmed");
  expect(emailCalls).toBe(1);
  await dialog.getByRole("button", { name: "Back to message", exact: true }).click();
  await expect(page.getByLabel("Email message", { exact: true })).toHaveValue("Hello <script>plain text</script>");
  await page.getByRole("button", { name: "Review email", exact: true }).click();
  await dialog.getByRole("button", { name: "Send email", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("status").filter({ hasText: "Email accepted" })).toBeVisible();
  expect(emailCalls).toBe(2);
  await page.setViewportSize({ width: 320, height: 568 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("tab", { name: "SMS", exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "D:/Project/workspace/.tmp/communications-sms-mobile.png", fullPage: true });
  expect(errors).toEqual([]);
});


test("Communications customer recipients support pagination, server search and custom contacts during lookup errors", async ({ page }) => {
  page.setDefaultTimeout(15000);
  await browserLogin(page, "staff@example.test");
  let failContacts = false;
  const lookups: string[] = [];
  await page.route("**/api/users/customers?*", route => {
    const url = new URL(route.request().url()); lookups.push(url.search);
    if (failContacts) return route.fulfill({ status: 503, json: { message: "Unavailable" } });
    const all = Array.from({ length: 11 }, (_, i) => ({ id: i + 1, name: i === 10 ? "Target customer" : `Customer ${i + 1}`, company_name: "Company", phone_number: `099000000${String(i + 1).padStart(2, "0")}`, email: `contact${i + 1}@example.test` }));
    const search = url.searchParams.get("search")?.toLowerCase() ?? "";
    const rows = all.filter(item => `${item.name} ${item.email} ${item.phone_number}`.toLowerCase().includes(search));
    const start = Number(url.searchParams.get("page") ?? 0) * 10;
    return route.fulfill({ json: { rows: rows.slice(start, start + 10), total: rows.length } });
  });
  await page.goto("/panel/communications");
  const phone = page.getByRole("combobox", { name: "Phone number", exact: true });
  await phone.click();
  await expect(page.getByRole("option").filter({ hasText: "Customer 1 /" })).toBeVisible();
  await page.getByRole("button", { name: "Next", exact: true }).click();
  await page.getByRole("option").filter({ hasText: "Target customer" }).click();
  await expect(phone).toHaveValue("09900000011");
  expect(lookups.some(url => url.includes("page=1") && url.includes("contact=phone"))).toBe(true);
  await phone.fill("Target");
  await expect(page.getByRole("option").filter({ hasText: "Target customer" })).toBeVisible();
  expect(lookups.some(url => url.includes("search=Target") && url.includes("page=0"))).toBe(true);
  await page.getByRole("option").filter({ hasText: "Target customer" }).click();
  await page.getByRole("tab", { name: "Email", exact: true }).click();
  const email = page.getByRole("combobox", { name: "Recipient email", exact: true });
  await email.fill("Target");
  await page.getByRole("option").filter({ hasText: "contact11@example.test" }).click();
  await expect(email).toHaveValue("contact11@example.test");
  await email.fill("invalid-email");
  await expect(page.getByRole("option", { name: /Use custom:/ })).toHaveCount(0);
  await page.keyboard.press("Escape");
  failContacts = true;
  await email.fill("outside@example.test");
  await expect(page.getByRole("alert").filter({ hasText: "Customer contacts could not be loaded" })).toBeVisible();
  await page.getByRole("option", { name: "Use custom: outside@example.test", exact: true }).click();
  await expect(email).toHaveValue("outside@example.test");
  await expect(page.getByLabel("Phone number", { exact: true })).toHaveCount(1);
});
