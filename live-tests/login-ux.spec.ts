import { expect, test } from "@playwright/test";
import { password } from "./helpers";

test.setTimeout(120_000);
test("Login UI supports mobile layout, password visibility, validation, network recovery and real sign-in", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/");
  const email = page.getByLabel("Email address", { exact: true });
  const secret = page.getByLabel("Password", { exact: true });
  const submit = page.getByRole("button", { name: "Login", exact: true });
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible();
  await expect(email).toHaveAttribute("autocomplete", "username");
  await expect(secret).toHaveAttribute("autocomplete", "current-password");
  await expect(email).toHaveValue(""); await expect(secret).toHaveValue("");
  await page.screenshot({ path: "D:/Project/workspace/.tmp/login-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "D:/Project/workspace/.tmp/login-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 320, height: 568 });
  await page.evaluate(() => { document.documentElement.style.fontSize = "20px"; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await expect(page.getByText("Contact your HYOps administrator", { exact: false })).toBeVisible();
  await page.evaluate(() => { document.documentElement.style.fontSize = ""; });
  await page.setViewportSize({ width: 390, height: 844 });
  let calls = 0;
  page.on("request", request => { if (request.url().endsWith("/api/auth/login") && request.method() === "POST") calls++; });
  await submit.click();
  await expect(email).toHaveAttribute("aria-invalid", "true");
  await expect(secret).toHaveAttribute("aria-invalid", "true");
  expect(calls).toBe(0);
  await email.fill("admin@example.test"); await secret.fill(password);
  await page.getByRole("button", { name: "Show password", exact: true }).click();
  await expect(secret).toHaveAttribute("type", "text");
  await expect(secret).toHaveValue(password);
  await page.getByRole("button", { name: "Hide password", exact: true }).click();
  await expect(secret).toHaveAttribute("type", "password");
  expect(calls).toBe(0);
  await secret.dispatchEvent("keyup", { key: "A", modifierCapsLock: true });
  await expect(page.getByText("Caps Lock is on.", { exact: true })).toBeVisible();
  await secret.dispatchEvent("keyup", { key: "A", modifierCapsLock: false });
  await expect(page.getByText("Caps Lock is on.", { exact: true })).toHaveCount(0);

  await page.route("**/api/auth/login", route => route.abort());
  await submit.click();
  await expect(page.getByRole("alert", { name: "Sign-in error", exact: true })).toContainText("Unable to connect");
  await expect(submit).toBeEnabled();
  await expect(secret).toHaveValue(password);
  await page.unroute("**/api/auth/login");
  await page.route("**/api/auth/login", route => route.fulfill({ status: 400, json: { errors: { email: "Invalid credentials." } } }));
  await submit.click();
  await expect(page.locator("#email-error")).toContainText("Invalid credentials.");
  await expect(email).toBeFocused();
  await expect(submit).toBeEnabled();
  await page.unroute("**/api/auth/login");
  await page.route("**/api/auth/login", route => route.fulfill({ status: 503, contentType: "text/plain", body: "Service unavailable" }));
  await submit.click();
  await expect(page.getByRole("alert", { name: "Sign-in error", exact: true })).toContainText("Sign-in is temporarily unavailable");
  await page.unroute("**/api/auth/login");

  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/api/auth/login", async route => { await gate; await route.continue(); });
  const before = calls;
  await submit.click();
  await expect(page.getByRole("button", { name: "Signing in...", exact: true })).toBeDisabled();
  await secret.press("Enter");
  expect(calls).toBe(before + 1);
  release();
  await expect(page).toHaveURL(/\/panel$/, { timeout: 30000 });
  expect(errors).toEqual([]);
});
